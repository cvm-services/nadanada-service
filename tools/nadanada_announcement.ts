/**
 * nadanada_announcement.ts — the ONE description of the nadanada-service CEP-6
 * announcement.
 *
 * The contract surface (d, cvm:service:*, cvm:req:*, cvm:opt:*, cvm:tier:*,
 * cap, r) is emitted ONLY by the vendored `cvm-service-kit`; this file is the
 * single place the input is described, so the Python announce path and the
 * golden fixture cannot drift from the shared contract.
 *
 * CLI:
 *   deno run --allow-read tools/nadanada_announcement.ts --emit     # print tags
 *   deno run --allow-read --allow-write tools/nadanada_announcement.ts --fixture
 *   deno run --allow-read tools/nadanada_announcement.ts --check    # fail on drift
 */
import {
  type AnnounceInput,
  assertAnnouncementTags,
  emitAnnouncementTags,
} from "../vendor/cvm-service-kit/src/mod.ts";
import { parseVocab, type Vocab } from "../vendor/cvm-service-kit/src/vocab.ts";

export const ANNOUNCEMENT_KIND = 11316;

/** The contract URL, carried by the `r` tag and by the CVM `docs` tool. */
export const CONTRACT_URL = "https://nadanada.orangesync.tech/cvm/llms.txt";

/**
 * Flat price, in sats, for one `phone.messages.list`. The advertised cap MUST
 * equal what the server charges; the Python side reads this same fixture, so
 * there is one number.
 */
export const PRICE_SATS = 1000;

/**
 * The declared flow input is money and nothing else. The phone number is a tool
 * argument, not a flow input, so declaring it would be the inflated appetite
 * the register forbids. That makes the recomputed tier `financial`.
 */
export const NADANADA_INPUT: AnnounceInput = {
  serviceClass: "phone-inbox",
  d: "nadanada",
  humanTags: ["sms-inbox", "contextvm"],
  required: ["payment.amount"],
  tools: { "phone.messages.list": { amount: PRICE_SATS } },
  urls: [CONTRACT_URL],
};

export const PAYLOAD_TAGS: string[][] = [
  ["name", "nadanada"],
  [
    "about",
    "Read inbound SMS on a rented nadanada number over ContextVM. Owner-free for the operator; pay per read in Cashu. The phone-account secret is never returned to the caller.",
  ],
  ["website", CONTRACT_URL],
];

/**
 * CEP-8 payment declaration, appended by the caller because the vendored kit
 * has no `pmi` support yet (same gap the nosms S5a card recorded). This is NOT
 * forking the kit: the contract surface is still emitted only by the kit.
 */
export const PAYMENT_TAGS: string[][] = [
  ["pmi", "bitcoin-cashu", "explicit_gating"],
];

export interface NadanadaAnnouncement {
  kind: number;
  contract_tags: string[][];
  payment_tags: string[][];
  payload_tags: string[][];
  tags: string[][];
  tier: string;
  warnings: string[];
}

export function buildNadanadaAnnouncement(vocab: Vocab): NadanadaAnnouncement {
  const { tags: contract_tags, tier, warnings } = emitAnnouncementTags(NADANADA_INPUT, vocab);
  const tags = [...contract_tags, ...PAYMENT_TAGS, ...PAYLOAD_TAGS];
  assertAnnouncementTags(tags, vocab);
  return { kind: ANNOUNCEMENT_KIND, contract_tags, payment_tags: PAYMENT_TAGS,
           payload_tags: PAYLOAD_TAGS, tags, tier, warnings };
}

export function loadVocab(
  path = new URL("../vendor/cvm-service-kit/vocab/service-inputs.json", import.meta.url),
): Vocab {
  return parseVocab(JSON.parse(Deno.readTextFileSync(path)));
}

if (import.meta.main) {
  const fixturePath = new URL("../fixtures/nadanada-11316.tags.json", import.meta.url);
  const vocab = loadVocab();
  const ann = buildNadanadaAnnouncement(vocab);
  const fixture = {
    _comment:
      "GOLDEN FIXTURE — generated by tools/nadanada_announcement.ts from the vendored " +
      "cvm-service-kit emitter. Do not hand-edit: regenerate with `--fixture` and review the diff.",
    _generated_by: "tools/nadanada_announcement.ts",
    kind: ann.kind,
    input: NADANADA_INPUT,
    price_sats: PRICE_SATS,
    contract_url: CONTRACT_URL,
    tier: ann.tier,
    warnings: ann.warnings,
    contract_tags: ann.contract_tags,
    payment_tags: ann.payment_tags,
    payload_tags: ann.payload_tags,
    tags: ann.tags,
  };
  const mode = Deno.args[0] ?? "--emit";
  if (mode === "--emit") {
    console.log(JSON.stringify(ann.tags));
  } else if (mode === "--fixture") {
    Deno.writeTextFileSync(fixturePath, JSON.stringify(fixture, null, 2) + "\n");
    console.log(`wrote ${fixturePath.pathname}`);
  } else if (mode === "--check") {
    const onDisk = JSON.parse(Deno.readTextFileSync(fixturePath));
    const strip = (o: Record<string, unknown>) => {
      const { _comment, _generated_by, ...rest } = o;
      void _comment; void _generated_by;
      return rest;
    };
    if (JSON.stringify(strip(onDisk)) !== JSON.stringify(strip(fixture))) {
      console.error("fixture drifted from the kit emitter");
      Deno.exit(1);
    }
    console.log("fixture matches the kit emitter");
  } else {
    console.error(`unknown mode ${mode} (use --emit | --fixture | --check)`);
    Deno.exit(2);
  }
}
