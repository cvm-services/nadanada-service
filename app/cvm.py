def load_announcement_tags(path: pathlib.Path | None = None) -> list[list[str]]:
    """The conformant CEP-6 tag set from the golden fixture (kit-emitted)."""
    p = path or FIXTURE_PATH
    fixture = json.loads(p.read_text())
    return [list(t) for t in fixture["tags"]]


def load_fixture(path: pathlib.Path | None = None) -> dict:
    p = path or FIXTURE_PATH
    return json.loads(p.read_text())
